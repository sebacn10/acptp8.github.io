<h2>2. Componentes Básicos del Hardware</h2>
<h3>La placa Arduino</h3>
<p>Conocé sus partes principales: pines digitales, pines analógicos, puerto USB y alimentación.</p>
<p>Cada una de estas secciones cumple una función clave: los pines digitales leen o envían señales de encendido y apagado (1 o 0), mientras que los pines analógicos leen rangos variables de voltaje proporcionados por sensores ambientales. La entrada de alimentación garantiza el voltaje adecuado para evitar fallas eléctricas en los componentes conectados.</p>
</section>
