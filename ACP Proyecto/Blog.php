<div class="article-block">
<h3>¿Qué es el IDE?</h3>
<p>Es el programa que usamos para escribir y cargar código a la placa.</p>
<p>El IDE (Entorno de Desarrollo Integrado) de Arduino proporciona un editor de texto con herramientas dedicadas para verificar la sintaxis de tu código, compilar las instrucciones en lenguaje máquina y subirlas directamente a la memoria flash de tu microcontrolador mediante una conexión USB estándar.</p>
</div>
<div class="article-block">
<h3>Instalación y Configuración Inicial</h3>
<p>Descargalo desde la página oficial y seguí los pasos básicos.</p>
<p>Para comenzar a programar, debes descargar el instalador oficial correspondiente a tu sistema operativo (Windows, macOS o Linux). Una vez completada la instalación, conecta tu placa Arduino, selecciona el puerto COM adecuado en el menú de herramientas y asegúrate de elegir el modelo de placa correcto antes de subir tu primer programa (sketch).</p>
</div>
<div class="article-block">
<h3>Estructura Básica de un Programa en Arduino</h3>
<p>Todo código escrito en este entorno de desarrollo incluye dos funciones principales indispensablemente: setup() y loop(). La función setup() ejecuta las configuraciones iniciales una sola vez al encender el circuito, mientras que la función loop() repite indefinidamente sus instrucciones mientras la placa reciba energía eléctrica.</p>
